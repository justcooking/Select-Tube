package com.selecttube.app.data.youtube

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.exceptions.ExtractionException
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.Description
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamSegment
import org.schabi.newpipe.extractor.stream.VideoStream
import java.io.IOException
import java.util.Locale
import javax.inject.Inject
import javax.inject.Singleton

sealed class PlayableStream {
    data class Adaptive(
        val videoUrl: String,
        val audioUrl: String,
        val videoQuality: String,
        val audioBitrate: Int,
        val audioTrack: String? = null,
        val width: Int = 0,
        val height: Int = 0,
    ) : PlayableStream()

    data class Progressive(
        val streamUrl: String,
        val quality: String,
        val width: Int = 0,
        val height: Int = 0,
    ) : PlayableStream()
}

enum class DescriptionType {
    PLAIN_TEXT,
    HTML,
    MARKDOWN,
}

data class SubtitleTrackInfo(
    val languageCode: String,
    val displayName: String,
    val url: String,
    val mimeType: String,
    val isAutoGenerated: Boolean = false,
)

data class ChapterInfo(
    val title: String,
    val startSeconds: Long,
)

data class ResolvedPlaybackInfo(
    val videoId: String,
    val title: String,
    val channelName: String,
    val channelId: String,
    val thumbnailUrl: String?,
    val durationSeconds: Long,
    val stream: PlayableStream,
    val originalUrl: String,
    val viewCount: Long = -1L,
    val likeCount: Long = -1L,
    val subscriberCount: Long = -1L,
    val channelAvatarUrl: String? = null,
    val availableQualities: List<String> = emptyList(),
    val availableAudioTracks: List<String> = emptyList(),
    val availableSubtitles: List<SubtitleTrackInfo> = emptyList(),
    val audioTrack: String? = null,
    val description: String? = null,
    val descriptionType: DescriptionType = DescriptionType.PLAIN_TEXT,
    val chapters: List<ChapterInfo> = emptyList(),
    val videoWidth: Int = 0,
    val videoHeight: Int = 0,
)

class StreamResolutionException(message: String, cause: Throwable? = null) : Exception(message, cause)

/**
 * Resolves YouTube video URLs into playable streams using NewPipe Extractor.
 * Completely free of Android UI and Media3 dependencies so it can be reused in web/desktop targets.
 */
@Singleton
class StreamResolver @Inject constructor() {

    private val youtubeService = ServiceList.YouTube
    private val streamInfoCache = java.util.concurrent.ConcurrentHashMap<String, StreamInfo>()

    /**
     * Resolves a video to playable streams.
     * Prefers the best video-only stream up to 720p merged with the best audio stream.
     * Falls back to the best progressive stream if adaptive streams are unavailable.
     */
    suspend fun resolveStream(urlOrVideoId: String): ResolvedPlaybackInfo = withContext(Dispatchers.IO) {
        val fullUrl = normalizeToWatchUrl(urlOrVideoId)

        val streamInfo = try {
            StreamInfo.getInfo(youtubeService, fullUrl)
        } catch (e: ExtractionException) {
            throw StreamResolutionException(
                "Cannot play this video: ${e.message ?: "it may be private, age-restricted, or removed"}.",
                e,
            )
        } catch (e: IOException) {
            throw StreamResolutionException("Network error while loading video stream.", e)
        } catch (e: Exception) {
            throw StreamResolutionException("Failed to resolve video: ${e.localizedMessage ?: "unknown error"}", e)
        }

        streamInfoCache[fullUrl] = streamInfo

        val videoId = extractVideoId(fullUrl)
        val title = streamInfo.name.orEmpty().ifBlank { "Untitled Video" }
        val channelName = streamInfo.uploaderName.orEmpty()
        val channelId = streamInfo.uploaderUrl?.substringAfterLast("/").orEmpty()
        val thumbnailUrl = streamInfo.thumbnails?.lastOrNull()?.url ?: streamInfo.thumbnails?.firstOrNull()?.url
        val durationSeconds = streamInfo.duration

        val viewCount = streamInfo.viewCount
        val likeCount = streamInfo.likeCount
        val subscriberCount = streamInfo.uploaderSubscriberCount
        val channelAvatarUrl = streamInfo.uploaderAvatars?.lastOrNull()?.url

        val availableQualities = (streamInfo.videoOnlyStreams.orEmpty() + streamInfo.videoStreams.orEmpty())
            .mapNotNull { if (it.height > 0) "${it.height}p" else null }
            .distinct()
            .sortedByDescending { it.removeSuffix("p").toIntOrNull() ?: 0 }

        val availableAudioTracks = streamInfo.audioStreams.orEmpty()
            .filter { it.isUrl && !it.content.isNullOrBlank() }
            .map { getAudioTrackDisplayName(it) }
            .distinct()

        val availableSubtitles = streamInfo.subtitles.orEmpty()
            .filter { it.isUrl && !it.content.isNullOrBlank() }
            .map { sub ->
                val rawUrl = sub.content.orEmpty()
                var vttUrl = when {
                    rawUrl.contains(Regex("[?&]fmt=")) -> {
                        rawUrl.replace(Regex("([?&])fmt=[^&]*")) { "${it.groupValues[1]}fmt=vtt" }
                    }
                    rawUrl.contains("?") -> "$rawUrl&fmt=vtt"
                    else -> "$rawUrl?fmt=vtt"
                }

                val langCode = sub.languageTag.orEmpty().ifBlank { sub.locale?.language.orEmpty() }
                if (langCode.isNotBlank()) {
                    val urlLangMatch = Regex("[?&]lang=([^&]+)").find(vttUrl)
                    val urlLang = urlLangMatch?.groupValues?.get(1)
                    if (urlLang != null && !urlLang.equals(langCode, ignoreCase = true)) {
                        vttUrl = vttUrl.replace(Regex("[?&]name=[^&]*"), "")
                        val targetCode = sub.locale?.language?.takeIf { it.isNotBlank() }
                            ?: langCode.substringBefore("-").substringBefore("_")
                        vttUrl = if (vttUrl.contains(Regex("[?&]tlang="))) {
                            vttUrl.replace(Regex("([?&])tlang=[^&]*")) { "${it.groupValues[1]}tlang=$targetCode" }
                        } else {
                            "$vttUrl&tlang=$targetCode"
                        }
                    }
                }
                val displayName = sub.displayLanguageName.orEmpty().ifBlank {
                    sub.locale?.getDisplayName(Locale.ENGLISH).orEmpty().ifBlank { "Unknown" }
                }
                SubtitleTrackInfo(
                    languageCode = langCode,
                    displayName = displayName,
                    url = vttUrl,
                    mimeType = "text/vtt",
                    isAutoGenerated = sub.isAutoGenerated,
                )
            }
            .distinctBy { it.displayName }

        val playableStream = choosePlayableStream(streamInfo)
            ?: throw StreamResolutionException("No playable streams found for this video.")

        val chosenAudioTrack = when (playableStream) {
            is PlayableStream.Adaptive -> playableStream.audioTrack
            is PlayableStream.Progressive -> availableAudioTracks.firstOrNull()
        }

        val rawDescription = streamInfo.description
        val descriptionText = rawDescription?.content?.takeIf { it.isNotBlank() }
        val descriptionType = when (rawDescription?.type) {
            Description.HTML -> DescriptionType.HTML
            Description.MARKDOWN -> DescriptionType.MARKDOWN
            else -> DescriptionType.PLAIN_TEXT
        }

        val chapters = extractChapters(streamInfo.streamSegments, descriptionText)

        val isShort = fullUrl.contains("/shorts/")
        val (streamW, streamH) = when (playableStream) {
            is PlayableStream.Adaptive -> Pair(playableStream.width, playableStream.height)
            is PlayableStream.Progressive -> Pair(playableStream.width, playableStream.height)
        }
        val resolvedWidth = if (streamW > 0) streamW else if (isShort) 1080 else 0
        val resolvedHeight = if (streamH > 0) streamH else if (isShort) 1920 else 0

        ResolvedPlaybackInfo(
            videoId = videoId,
            title = title,
            channelName = channelName,
            channelId = channelId,
            thumbnailUrl = thumbnailUrl,
            durationSeconds = durationSeconds,
            stream = playableStream,
            originalUrl = fullUrl,
            viewCount = viewCount,
            likeCount = likeCount,
            subscriberCount = subscriberCount,
            channelAvatarUrl = channelAvatarUrl,
            availableQualities = availableQualities,
            availableAudioTracks = availableAudioTracks,
            availableSubtitles = availableSubtitles,
            audioTrack = chosenAudioTrack,
            description = descriptionText,
            descriptionType = descriptionType,
            chapters = chapters,
            videoWidth = resolvedWidth,
            videoHeight = resolvedHeight,
        )
    }

    private fun extractChapters(
        streamSegments: List<StreamSegment>?,
        descriptionText: String?,
    ): List<ChapterInfo> {
        val segmentChapters = try {
            streamSegments?.mapNotNull { seg ->
                val title = seg.title?.trim()?.takeIf { it.isNotEmpty() } ?: return@mapNotNull null
                ChapterInfo(
                    title = title,
                    startSeconds = seg.startTimeSeconds.toLong().coerceAtLeast(0L),
                )
            }
        } catch (_: Exception) {
            null
        }

        if (!segmentChapters.isNullOrEmpty()) {
            return segmentChapters
        }

        if (descriptionText.isNullOrBlank()) return emptyList()

        val startPattern = Regex(
            """^\s*[-•*]?\s*(?:\[|\()?((\d{1,2}:)?[0-5]?\d:[0-5]\d)(?:\]|\))?\s*[-–—:]?\s*(.+)$"""
        )
        val endPattern = Regex(
            """^\s*(.+?)\s*[-–—:]?\s*(?:\[|\()?((\d{1,2}:)?[0-5]?\d:[0-5]\d)(?:\]|\))?\s*$"""
        )

        val parsed = mutableListOf<ChapterInfo>()
        for (line in descriptionText.lines()) {
            val trimmed = line.trim()
            if (trimmed.isEmpty()) continue

            val startMatch = startPattern.find(trimmed)
            if (startMatch != null) {
                val tsStr = startMatch.groupValues[1]
                val rawTitle = startMatch.groupValues[3].trim()
                val title = rawTitle.removePrefix("-").removePrefix("–").removePrefix("—").removePrefix(":").trim()
                val sec = parseTimestampToSeconds(tsStr)
                if (sec != null && title.isNotEmpty()) {
                    parsed.add(ChapterInfo(title = title, startSeconds = sec))
                    continue
                }
            }

            val endMatch = endPattern.find(trimmed)
            if (endMatch != null) {
                val rawTitle = endMatch.groupValues[1].trim()
                val tsStr = endMatch.groupValues[2]
                val title = rawTitle.removePrefix("-").removePrefix("–").removePrefix("—").removePrefix(":").trim()
                val sec = parseTimestampToSeconds(tsStr)
                if (sec != null && title.isNotEmpty()) {
                    parsed.add(ChapterInfo(title = title, startSeconds = sec))
                }
            }
        }

        return if (parsed.size >= 2) {
            parsed.distinctBy { it.startSeconds }.sortedBy { it.startSeconds }
        } else {
            emptyList()
        }
    }

    private fun parseTimestampToSeconds(ts: String): Long? {
        val parts = ts.split(':').mapNotNull { it.toLongOrNull() }
        return when (parts.size) {
            2 -> parts[0] * 60L + parts[1]
            3 -> parts[0] * 3600L + parts[1] * 60L + parts[2]
            else -> null
        }
    }

    /**
     * Re-resolves a previously resolved stream to obtain fresh playback URLs if expired.
     */
    suspend fun reResolve(previous: ResolvedPlaybackInfo): ResolvedPlaybackInfo {
        return resolveStream(previous.originalUrl)
    }

    /**
     * Obtains a PlayableStream for a specific target quality using cached StreamInfo.
     */
    fun resolveQuality(originalUrl: String, quality: String, currentAudioTrack: String? = null): PlayableStream? {
        val streamInfo = streamInfoCache[originalUrl] ?: return null
        return choosePlayableStream(streamInfo, targetQuality = quality, targetAudioTrack = currentAudioTrack)
    }

    /**
     * Obtains a PlayableStream for a specific target audio track using cached StreamInfo.
     */
    fun resolveAudioTrack(originalUrl: String, audioTrack: String, currentQuality: String? = null): PlayableStream? {
        val streamInfo = streamInfoCache[originalUrl] ?: return null
        return choosePlayableStream(streamInfo, targetQuality = currentQuality, targetAudioTrack = audioTrack)
    }

    private fun getAudioTrackDisplayName(stream: AudioStream): String {
        val trackName = stream.audioTrackName?.trim()?.takeIf { it.isNotEmpty() }
        if (trackName != null) return trackName
        val localeName = stream.audioLocale?.getDisplayName(java.util.Locale.ENGLISH)?.trim()?.takeIf { it.isNotEmpty() }
        if (localeName != null) return localeName
        return "Default"
    }

    /**
     * Selects the best stream:
     * 1. Best video-only stream <= 720p (or targetQuality) + best audio-only stream matching targetAudioTrack.
     * 2. Fallback: best progressive stream <= 720p (or best progressive available).
     */
    fun choosePlayableStream(
        streamInfo: StreamInfo,
        targetQuality: String? = null,
        targetAudioTrack: String? = null,
    ): PlayableStream? {
        val videoOnlyStreams = streamInfo.videoOnlyStreams.orEmpty()
            .filter { it.isUrl && !it.content.isNullOrBlank() }
        val audioStreams = streamInfo.audioStreams.orEmpty()
            .filter { it.isUrl && !it.content.isNullOrBlank() }

        val targetHeight = targetQuality?.removeSuffix("p")?.toIntOrNull()

        // 1. Try best video-only stream
        val candidateVideos = if (targetHeight != null) {
            videoOnlyStreams.filter { it.height == targetHeight }
                .ifEmpty {
                    videoOnlyStreams.filter { it.height <= targetHeight }.sortedByDescending { it.height }
                }
        } else {
            videoOnlyStreams
                .filter { it.height in 1..720 }
                .sortedByDescending { it.height }
                .ifEmpty {
                    videoOnlyStreams.sortedBy { it.height }
                }
        }

        val bestVideo = candidateVideos.firstOrNull() ?: videoOnlyStreams.maxByOrNull { it.height }

        val candidateAudios = if (targetAudioTrack != null) {
            audioStreams.filter { getAudioTrackDisplayName(it).equals(targetAudioTrack, ignoreCase = true) }
                .ifEmpty { audioStreams }
        } else {
            val originalStreams = audioStreams.filter {
                it.audioTrackType?.name == "ORIGINAL" ||
                    it.audioTrackName?.contains("original", ignoreCase = true) == true
            }
            if (originalStreams.isNotEmpty()) originalStreams else audioStreams
        }

        val bestAudio = candidateAudios.maxByOrNull { it.averageBitrate } ?: audioStreams.maxByOrNull { it.averageBitrate }

        if (bestVideo != null && bestAudio != null) {
            val videoUrl = bestVideo.content
            val audioUrl = bestAudio.content
            if (!videoUrl.isNullOrBlank() && !audioUrl.isNullOrBlank()) {
                val quality = if (bestVideo.height > 0) "${bestVideo.height}p" else "720p"
                val audioTrackName = getAudioTrackDisplayName(bestAudio)
                return PlayableStream.Adaptive(
                    videoUrl = videoUrl,
                    audioUrl = audioUrl,
                    videoQuality = quality,
                    audioBitrate = bestAudio.averageBitrate,
                    audioTrack = audioTrackName,
                    width = bestVideo.width,
                    height = bestVideo.height,
                )
            }
        }

        // 2. Fallback to progressive streams (video + audio combined)
        val progressiveStreams = streamInfo.videoStreams.orEmpty()
            .filter { it.isUrl && !it.content.isNullOrBlank() }

        val bestProgressive = if (targetHeight != null) {
            progressiveStreams.firstOrNull { it.height == targetHeight }
                ?: progressiveStreams.maxByOrNull { it.height }
        } else {
            progressiveStreams
                .filter { it.height in 1..720 }
                .maxByOrNull { it.height }
                ?: progressiveStreams.firstOrNull()
        }

        if (bestProgressive != null) {
            val streamUrl = bestProgressive.content
            if (!streamUrl.isNullOrBlank()) {
                val quality = if (bestProgressive.height > 0) "${bestProgressive.height}p" else "360p"
                return PlayableStream.Progressive(
                    streamUrl = streamUrl,
                    quality = quality,
                    width = bestProgressive.width,
                    height = bestProgressive.height,
                )
            }
        }

        return null
    }

    private fun normalizeToWatchUrl(input: String): String {
        val trimmed = input.trim()
        return when {
            trimmed.startsWith("http://") || trimmed.startsWith("https://") -> trimmed
            else -> "https://www.youtube.com/watch?v=$trimmed"
        }
    }

    private fun extractVideoId(url: String): String {
        return url.substringAfterLast("v=").substringBefore("&")
            .ifBlank { url.substringAfterLast("/") }
    }
}
